"""Tests for exception-safe program-generation context managers."""

import pytest
import origen_metal._origen_metal as om


@pytest.fixture(autouse=True)
def reset_program_generator():
    """Reset global program-generation state around every test."""
    om.prog_gen.reset()
    yield
    om.prog_gen.reset()


@pytest.mark.parametrize("context_name",
                         ["group", "condition", "resources", "loop"])
def test_context_closes_when_body_raises(context_name):
    """An exceptional context exit must not leave its AST node open."""
    interface = om.interface.PyInterface()
    outer_refs = om.prog_gen.start_new_flow("outer", None, None, None)
    child_refs = om.prog_gen.start_new_flow("child", True, None, None)

    if context_name == "group":
        context = interface.group("group", if_flag="enabled")
    elif context_name == "condition":
        context = interface.if_flag("enabled")
    elif context_name == "loop":
        context = interface.loop(3, if_flag="enabled")
    else:
        context = interface.resources()

    with pytest.raises(RuntimeError, match="sentinel"):
        with context:
            raise RuntimeError("sentinel")

    om.prog_gen.end_flow(child_refs)
    om.prog_gen.end_flow(outer_refs)


def _flow_ast(build):
    """Return the AST string of a flow whose content is generated by build."""
    interface = om.interface.PyInterface()
    refs = om.prog_gen.start_new_flow("flow", None, None, None)
    build(interface)
    om.prog_gen.end_flow(refs)
    return om.prog_gen.ast_str()


def test_expression_conditions_are_context_managers_and_flow_options():
    def build(interface):
        with interface.if_expr("mode == 6"):
            interface.set_flag("in_context")
        with interface.unless_expr("mode == 6"):
            interface.set_variable("count", "0")
        with interface.group("grp", if_expr="a > 1", unless_expr="b > 2"):
            interface.set_flag("in_group")

    ast = _flow_ast(build)
    assert 'Condition(IfExpr("mode == 6"))\n        SetFlag("in_context", true, false)' in ast
    assert 'Condition(UnlessExpr("mode == 6"))\n        SetVariable("count", "0")' in ast
    assert 'Condition(IfExpr("a > 1"))\n        Condition(UnlessExpr("b > 2"))\n            Group("grp"' in ast


@pytest.mark.parametrize("name", ["if_expr", "unless_expr"])
def test_expression_condition_must_be_a_single_string(name):
    interface = om.interface.PyInterface()
    with pytest.raises(TypeError, match="expected a String expression"):
        getattr(interface, name)(["a > 1", "b > 2"])


def test_resources_keep_flows_only_when_asked():
    def build(interface):
        with interface.resources():
            interface.set_flag("plain")
        with interface.resources(keep_flows=False):
            interface.set_flag("not_kept")
        with interface.resources(keep_flows=True):
            interface.set_flag("kept")

    ast = _flow_ast(build)
    assert '    Resources\n        SetFlag("plain", true, false)' in ast
    assert '    Resources\n        SetFlag("not_kept", true, false)' in ast
    assert '    ResourcesKeepFlows\n        SetFlag("kept", true, false)' in ast


def test_loop_applies_flow_options_around_the_loop():
    def build(interface):
        with interface.loop(3, "attempt", if_enable="retry"):
            interface.set_flag("looped")
        with interface.loop(9, descending=True):
            pass

    ast = _flow_ast(build)
    assert 'Condition(IfEnable(["retry"]))\n        Loop(Some(Fixed(3)), Some("attempt"), false, 1)\n            SetFlag("looped", true, false)' in ast
    assert 'Loop(Some(Fixed(9)), Some("index"), true, 1)' in ast


def test_loops_take_a_start_and_a_count_held_in_a_flow_variable():
    def build(interface):
        with interface.loop(6, "attempt", start=0):
            pass
        with interface.loop("retryCount", "attempt", True):
            pass

    ast = _flow_ast(build)
    assert 'Loop(Some(Fixed(6)), Some("attempt"), false, 0)' in ast
    assert 'Loop(Some(Variable("retryCount")), Some("attempt"), true, 1)' in ast


@pytest.mark.parametrize("count,error,match", [
    (0, ValueError, "must be an integer from 1"),
    (-1, ValueError, "must be an integer from 1"),
    (2**32, ValueError, "must be an integer from 1"),
    ("1st", ValueError, "must be the name of a flow variable"),
    ("a b", ValueError, "must be the name of a flow variable"),
    (True, TypeError, "not 'bool'"),
    (3.0, TypeError, "not 'float'"),
    (None, TypeError, "not 'NoneType'"),
])
def test_loop_count_must_be_an_int_or_a_variable_name(count, error, match):
    interface = om.interface.PyInterface()
    refs = om.prog_gen.start_new_flow("flow", None, None, None)
    with pytest.raises(error, match=match):
        interface.loop(count, if_flag="enabled")
    # No condition was left open by the invalid loop
    om.prog_gen.end_flow(refs)
    assert "Loop" not in om.prog_gen.ast_str()
    assert "IfFlag" not in om.prog_gen.ast_str()


def test_bypassed_group_is_inside_its_conditions():
    def build(interface):
        with interface.group("grp", if_flag="f", if_enable="e", bypass=True):
            interface.set_flag("in_group")
        with interface.group("not_bypassed", bypass=False):
            pass

    ast = _flow_ast(build)
    assert 'Condition(IfEnable(["e"]))\n        Condition(IfFlag(["f"]))\n            BypassSubFlows\n                Group("grp"' in ast
    assert ast.count("BypassSubFlows") == 1


